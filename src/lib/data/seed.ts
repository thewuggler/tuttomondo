const placeholderImage = (seed: string) =>
  `https://picsum.photos/seed/${seed}/1200/1500`;

const hueFor = (seed: string) => {
  let h = 0;
  for (let i = 0; i < seed.length; i++) h = (h * 31 + seed.charCodeAt(i)) >>> 0;
  return `${h % 360}`;
};

